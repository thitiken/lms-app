export const ALL_SCENARIOS: ScenarioDefinition[] = [EXAMPLE_SCENARIO, ...GLOBAL_SCENARIOS];

export function getScenarioById(id: string): ScenarioDefinition {
  return ALL_SCENARIOS.find((s) => s.id === id) || EXAMPLE_SCENARIO;
}

export function getScenarioForGroup(groupId: number): ScenarioDefinition {
  return GLOBAL_SCENARIOS.find((s) => s.assignedGroups.includes(groupId)) || GLOBAL_SCENARIOS[0];
}

export function isJoinedStudent(rec: StudentScoreRecord): boolean {
  if (rec.joined === true) return true;
  if (rec.joined === false) return false;
  return !rec.studentName.startsWith('นักเรียน 67');
}
